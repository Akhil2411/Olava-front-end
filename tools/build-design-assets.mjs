#!/usr/bin/env node
/**
 * Builds the static assets of the wedding-site designs into public/designs/ (runs before `dev` and `build`).
 *
 * Each design's stylesheets (src/templates/designs/<design>/css/*.css) and each theme's fonts are served as their
 * own files, so a wedding website only downloads its own design, never all of them. Files get a content hash
 * in their name (safe to cache) and src/templates/designs/assets.generated.ts maps names to URLs.
 *
 * Fonts come from the @fontsource packages (self-hosted: guests' browsers never contact Google). Only the
 * Latin and Latin Extended subsets are copied; the browser downloads a file only when the page uses it.
 * The fonts each theme needs are listed in src/templates/designs/fonts.json.
 *
 *   node tools/build-design-assets.mjs
 * See docs/adding-templates.md.
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { transform } from "lightningcss";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "src/templates/designs");
const OUT = path.join(ROOT, "public/designs");
const FONTSOURCE = path.join(ROOT, "node_modules/@fontsource");
const SUBSETS = ["latin", "latin-ext"];

const hash = (data) => crypto.createHash("sha256").update(data).digest("hex").slice(0, 10);
const minify = (css, filename) =>
  transform({ filename, code: Buffer.from(css), minify: true, targets: { safari: 15 << 16, chrome: 100 << 16, firefox: 100 << 16 } }).code;

// Remove what this script generated before (not thumbs/, which tools/capture-thumbnails.mjs owns).
for (const entry of fs.existsSync(OUT) ? fs.readdirSync(OUT) : []) {
  if (entry !== "thumbs") fs.rmSync(path.join(OUT, entry), { recursive: true, force: true });
}
fs.mkdirSync(path.join(OUT, "fonts/files"), { recursive: true });
const manifest = { css: {}, fonts: {} };

// ── Design stylesheets ──
for (const design of fs.readdirSync(SRC)) {
  const dir = path.join(SRC, design, "css");
  if (!fs.existsSync(dir)) continue;
  fs.mkdirSync(path.join(OUT, design), { recursive: true });
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".css")).sort()) {
    const code = minify(fs.readFileSync(path.join(dir, file), "utf8"), file);
    const name = `${file.replace(/\.css$/, "")}.${hash(code)}.css`;
    fs.writeFileSync(path.join(OUT, design, name), code);
    manifest.css[`${design}/${file}`] = `/designs/${design}/${name}`;
  }
}

// ── Theme fonts ──
const fonts = JSON.parse(fs.readFileSync(path.join(SRC, "fonts.json"), "utf8"));
const copied = new Set();
for (const [theme, families] of Object.entries(fonts)) {
  if (theme.startsWith("$")) continue; // comments
  let css = "";
  for (const { family, normal = [], italic = [] } of families) {
    const id = family.toLowerCase().replace(/\s+/g, "-");
    const pkg = path.join(FONTSOURCE, id);
    if (!fs.existsSync(pkg)) throw new Error(`Missing @fontsource/${id} (npm install -D @fontsource/${id})`);
    for (const [weights, style] of [[normal, "normal"], [italic, "italic"]]) {
      for (const w of weights) {
        const source = path.join(pkg, `${w}${style === "italic" ? "-italic" : ""}.css`);
        if (!fs.existsSync(source)) throw new Error(`@fontsource/${id} has no ${w} ${style}`);
        // Blocks look like: /* id-latin-400-normal */ @font-face { ... unicode-range: ... }
        const text = fs.readFileSync(source, "utf8");
        for (const m of text.matchAll(/\/\* ([\w-]+) \*\/\s*(@font-face\s*{[^}]*})/g)) {
          const subset = SUBSETS.find((s) => m[1] === `${id}-${s}-${w}-${style}`);
          if (!subset) continue;
          const file = `${id}-${subset}-${w}-${style}.woff2`;
          if (!copied.has(file)) {
            fs.copyFileSync(path.join(pkg, "files", file), path.join(OUT, "fonts/files", file));
            copied.add(file);
          }
          css += m[2].replace(/src:[^;]*;/, `src: url(/designs/fonts/files/${file}) format('woff2');`) + "\n";
        }
      }
    }
  }
  const code = minify(css, `${theme}.css`);
  const name = `${theme}.${hash(code)}.css`;
  fs.writeFileSync(path.join(OUT, "fonts", name), code);
  manifest.fonts[theme] = `/designs/fonts/${name}`;
}

const ts = `// Generated by tools/build-design-assets.mjs. Do not edit by hand.
export const DESIGN_CSS: Record<string, string> = ${JSON.stringify(manifest.css, null, 2)};
export const THEME_FONTS: Record<string, string> = ${JSON.stringify(manifest.fonts, null, 2)};
`;
fs.writeFileSync(path.join(SRC, "assets.generated.ts"), ts);
const size = (dir) => fs.readdirSync(dir, { withFileTypes: true }).reduce((n, e) => n + (e.isDirectory() ? size(path.join(dir, e.name)) : fs.statSync(path.join(dir, e.name)).size), 0);
console.log(`design assets: ${Object.keys(manifest.css).length} stylesheets, ${Object.keys(manifest.fonts).length} theme font sets, ${copied.size} font files, ${(size(OUT) / 1024 / 1024).toFixed(1)} MB`);
