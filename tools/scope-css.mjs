#!/usr/bin/env node
/**
 * Scopes a supplied template stylesheet so it can live inside the Olava app without leaking.
 *
 *   node tools/scope-css.mjs --scope .olv-eg --prefix eg [--theme sage-garden] input.css > output.css
 *
 * - `:root`, `html` and `body` become the design's root element (`.olv-eg`, or
 *   `.olv-eg[data-theme="sage-garden"]` with --theme, for a colour theme's variables).
 *   `body.locked .x` becomes `.olv-eg.locked .x`.
 * - Every other selector is nested under the root: `.hero h1` → `.olv-eg .hero h1`.
 * - `@keyframes fade` becomes `@keyframes eg-fade` and every animation using it is renamed.
 * - Rules inside @media / @supports are scoped the same way.
 * See docs/adding-templates.md.
 */
import fs from "node:fs";
import postcss from "postcss";

const args = process.argv.slice(2);
const opt = (name) => { const i = args.indexOf(`--${name}`); return i >= 0 ? args.splice(i, 2)[1] : null; };
const scope = opt("scope");
const prefix = opt("prefix");
const theme = opt("theme");
const file = args[0];
if (!scope || !prefix || !file) {
  console.error("usage: scope-css.mjs --scope .olv-xx --prefix xx [--theme key] input.css");
  process.exit(1);
}
const root = theme ? `${scope}[data-theme="${theme}"]` : scope;

const css = postcss.parse(fs.readFileSync(file, "utf8"));

// Keyframes: collect names first, then rename definitions and uses.
const frames = new Set();
css.walkAtRules(/keyframes$/, (r) => frames.add(r.params.trim()));
css.walkAtRules(/keyframes$/, (r) => { r.params = `${prefix}-${r.params.trim()}`; });
const renameAnimation = (value) =>
  value.split(",").map((part) => part.replace(/[A-Za-z_][\w-]*/g, (word) => (frames.has(word) ? `${prefix}-${word}` : word))).join(",");
css.walkDecls(/^(animation|animation-name)$/, (d) => { d.value = renameAnimation(d.value); });

function scopeSelector(sel) {
  const s = sel.trim();
  if (!s) return s;
  // :root / html / body, alone or with classes/attributes/pseudo-classes attached ("body.locked", "html:focus-within")
  const m = s.match(/^(:root|html|body)((?:[.:[#][^\s>+~]*)?)(.*)$/);
  if (m) {
    const [, , attached, rest] = m;
    // "html body" or "html > body": collapse to the root
    const tail = rest.replace(/^\s*>?\s*body\b/, "");
    return `${root}${attached}${tail}`;
  }
  if (s.startsWith("*")) return `${root} ${s}`;
  if (s.startsWith("::")) return `${root} ${s}`;
  return `${root} ${s}`;
}

css.walkRules((rule) => {
  if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
  rule.selectors = rule.selectors.map(scopeSelector);
});

process.stdout.write(`/* Generated by tools/scope-css.mjs from ${file.split("/").slice(-2).join("/")} (scope ${root}). Edit the source design, then regenerate, or edit here deliberately. */\n`);
process.stdout.write(css.toString());
