#!/usr/bin/env node
/**
 * Captures a thumbnail of every template whose design exists (the opened invitation, phone-sized, 3:4) from the
 * running web app's sample pages, into public/designs/thumbs/, and writes src/templates/designs/thumbs.generated.ts.
 *
 *   npm run dev            (or next start; the API must be running for the catalogue)
 *   node tools/capture-thumbnails.mjs [--base http://localhost:3000] [--only key1,key2]
 *
 * Re-run after changing a design or adding a template. See docs/adding-templates.md.
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const opt = (name, fallback) => { const i = args.indexOf(`--${name}`); return i >= 0 ? args[i + 1] : fallback; };
const base = opt("base", "http://localhost:3000");
const only = opt("only", "")?.split(",").filter(Boolean) ?? [];
const OUT = path.join(ROOT, "public/designs/thumbs");
const MANIFEST = path.join(ROOT, "src/templates/designs/thumbs.generated.ts");

const html = await (await fetch(`${base}/templates`)).text();
const keys = [...new Set([...html.matchAll(/\/template-sample\/([a-z0-9-]+)|template=([a-z0-9-]+)/g)].map((m) => m[1] ?? m[2]))];
if (keys.length === 0) throw new Error(`No templates found at ${base}/templates (is the API running?)`);

const existing = fs.existsSync(MANIFEST) ? Object.fromEntries([...fs.readFileSync(MANIFEST, "utf8").matchAll(/"([a-z0-9-]+)": "([^"]+)"/g)].map((m) => [m[1], m[2]])) : {};
fs.mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch(process.env.PW_CHROMIUM_PATH ? { executablePath: process.env.PW_CHROMIUM_PATH } : {});
const result = { ...existing };
for (const key of keys.filter((k) => only.length === 0 || only.includes(k))) {
  const page = await browser.newPage({ viewport: { width: 390, height: 520 }, deviceScaleFactor: 1.5, reducedMotion: "reduce" });
  await page.goto(`${base}/template-sample/${key}`, { waitUntil: "networkidle" });
  await page.evaluate(() => document.fonts.ready);
  // Open the invitation if the design has an opening (doors, envelope…).
  const opener = page.locator("[data-olava-intro] button").first();
  if (await opener.count()) {
    // Some openings end on their own (Classic designs, with reduced motion at once), so the button may go first.
    await opener.click({ timeout: 3000 }).catch(() => {});
    await page.waitForTimeout(2600);
  }
  await page.addStyleTag({ content: ".olv-music { display: none !important; }" }); // no floating button in thumbnails
  await page.waitForTimeout(400);
  const shot = await page.screenshot({ type: "jpeg", quality: 82 });
  const name = `${key}.${crypto.createHash("sha256").update(shot).digest("hex").slice(0, 10)}.jpg`;
  if (existing[key]) fs.rmSync(path.join(ROOT, "public", existing[key]), { force: true });
  fs.writeFileSync(path.join(OUT, name), shot);
  result[key] = `/designs/thumbs/${name}`;
  console.log(`${key} → ${name}`);
  await page.close();
}
await browser.close();
const sorted = Object.fromEntries(Object.entries(result).sort(([a], [b]) => a.localeCompare(b)));
fs.writeFileSync(MANIFEST, `// Generated by tools/capture-thumbnails.mjs. Do not edit by hand.\nexport const THUMBS: Record<string, string> = ${JSON.stringify(sorted, null, 2)};\n`);
